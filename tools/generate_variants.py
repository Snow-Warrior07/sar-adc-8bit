"""Generate an explicit one-hot FSM; keep the externally observed state coding."""
import re
from tools.common import ROOT


def run():
    source=(ROOT/'rtl/sar_controller.sv').read_text()
    one,count=re.subn(r'localparam IDLE=3\x27d0,.*?DONE=3\x27d6;',
        "localparam IDLE=7'd1, ACQUIRE=7'd2, HOLD=7'd4, SET=7'd8, SETTLE=7'd16, EVAL=7'd32, DONE=7'd64;",source,flags=re.S)
    assert count==1
    one=one.replace('reg [2:0] state;','reg [6:0] state;')
    one=one.replace('assign state_debug = state;',
        'assign state_debug = state==IDLE ? 0 : state==ACQUIRE ? 1 : state==HOLD ? 2 : state==SET ? 3 : state==SETTLE ? 4 : state==EVAL ? 5 : 6;')
    path=ROOT/'rtl/sar_controller_onehot.sv'
    path.write_text('// Generated by tools/generate_variants.py; compile separately from binary implementation.\n'+one,encoding='utf-8')
    return path


if __name__=='__main__':print(run())
